import { test, expect } from '@playwright/test'
test.beforeEach(async ({ page }) => {
  await page.goto('examples/superhuman/index.html')
})
test('邮箱筛选、归档与撤销改变真实列表', async ({ page }) => {
  await expect(page.locator('.mail-item')).toHaveCount(2)
  await page.locator('[data-filter="all"]').click()
  await expect(page.locator('.mail-item')).toHaveCount(3)
  await page.locator('#archive').click()
  await expect(page.locator('.mail-item')).toHaveCount(2)
  await page.locator('[data-filter="archive"]').click()
  await expect(page.locator('#mail-subject')).toContainText('周四')
  await page.locator('#undo').click()
  await expect(page.locator('.mail-item')).toHaveCount(3)
})
test('回复草稿隔离到邮件，空值提示与命令面板可关闭', async ({ page }) => {
  await page.locator('#reply-form button').click()
  await expect(page.locator('#mail-status')).toContainText('先写下')
  await page.locator('#reply').fill('我会带上访谈摘录。')
  await page.locator('#reply-form button').click()
  await page.locator('[data-mail="invoice"]').click()
  await expect(page.locator('#reply')).toHaveValue('')
  await page.locator('[data-mail="design"]').click()
  await expect(page.locator('#reply')).toHaveValue('我会带上访谈摘录。')
  await page.locator('#commands').click()
  await expect(page.locator('#command-dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('#commands')).toBeFocused()
})
