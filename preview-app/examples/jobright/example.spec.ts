import { test, expect } from '@playwright/test'
test('three job dimensions yield an explainable match', async ({ page }) => {
  await page.goto('examples/jobright/index.html')
  await page.selectOption('#skill', 'development')
  await page.selectOption('#time', 'mid')
  await page.selectOption('#place', 'remote')
  await expect(page.locator('.project')).toHaveCount(1)
  await page.locator('[data-detail=frontend]').click()
  await expect(page.locator('#reason')).toContainText('该岗位同时满足')
  await page.keyboard.press('Escape')
  await expect(page.locator('#details')).toBeHidden()
  await expect(page.locator('[data-detail=frontend]')).toBeFocused()
})
test('saved jobs can be removed and empty combinations stay empty', async ({ page }) => {
  await page.goto('examples/jobright/index.html')
  await page.locator('[data-save=designer]').click()
  await page.check('#saved')
  await expect(page.locator('.project')).toHaveCount(1)
  await page.locator('[data-save=designer]').click()
  await expect(page.locator('#empty')).toBeVisible()
  await page.uncheck('#saved')
  await page.selectOption('#skill', 'data')
  await page.selectOption('#time', 'junior')
  await page.selectOption('#place', 'remote')
  await expect(page.locator('#empty')).toBeVisible()
})
