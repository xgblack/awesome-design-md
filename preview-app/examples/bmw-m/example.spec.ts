import { test, expect } from '@playwright/test'
test('bmw-m: 车型与场景交集、空结果与恢复', async ({ page }) => {
  await page.goto('examples/bmw-m/index.html')
  await page.locator('#model').selectOption('gt')
  await expect(page.locator('.stories article:visible')).toHaveCount(1)
  await page.locator('#track').selectOption('garage')
  await expect(page.locator('#track-status')).toHaveText('0 篇固定文化档案')
  await expect(page.locator('#archive-empty')).toBeVisible()
  await expect(page.locator('#model')).toHaveValue('gt')
  await page.locator('#reset-filters').click()
  await expect(page.locator('.stories article:visible')).toHaveCount(3)
})
test('bmw-m: 相册循环切换、过滤后的边界和关闭归焦', async ({ page }) => {
  await page.goto('examples/bmw-m/index.html')
  await page.locator('[data-gallery="0"]').click()
  await page.locator('#gallery-prev').click()
  await expect(page.locator('#gallery-caption')).toContainText('3 / 3')
  await expect(page.locator('#gallery-image')).toHaveAttribute('src', /closed-course/)
  await page.locator('#gallery-next').click()
  await expect(page.locator('#gallery-caption')).toContainText('1 / 3')
  await page.keyboard.press('Escape')
  await expect(page.locator('[data-gallery="0"]')).toBeFocused()
  await page.locator('#track').selectOption('garage')
  await page.locator('[data-gallery="1"]').click()
  await expect(page.locator('#gallery-caption')).toContainText('1 / 1')
  await expect(page.locator('#gallery-next')).toBeDisabled()
  await page.locator('#viewer-close').click()
  await expect(page.locator('[data-gallery="1"]')).toBeFocused()
})
