import { test, expect } from '@playwright/test'
test('uber: 路线端点、交换与两种交通方式真实改变图示', async ({ page }) => {
  await page.goto('examples/uber/index.html')
  await page.getByRole('button', { name: '查看演示路线' }).click()
  const first = await page.locator('#route-line').getAttribute('d')
  await expect(page.locator('#walk-time')).toHaveText('12 分钟')
  await page.locator('#mode-shuttle').click()
  await expect(page.locator('#route-line')).not.toHaveAttribute('d', first!)
  await expect(page.locator('#map-route-name')).toContainText('接驳')
  await page.locator('#swap').click()
  await expect(page.locator('#from')).toHaveValue('market')
  await expect(page.locator('#route-results')).toBeHidden()
  await expect(page.locator('#route-line')).toBeHidden()
  await page.getByRole('button', { name: '查看演示路线' }).click()
  await expect(page.locator('#route-line')).toHaveAttribute('d', /^M360 337.*L130 160$/)
  await page.locator('#to').selectOption('garden')
  await page.getByRole('button', { name: '查看演示路线' }).click()
  await expect(page.locator('#route-line')).toHaveAttribute('d', /^M360 337.*L165 510$/)
  await expect(page.locator('#walk-time')).toHaveText('9 分钟')
})
test('uber: 同点和未接入错误清除旧成功路径，修正后无障碍绕行', async ({ page }) => {
  await page.goto('examples/uber/index.html')
  await page.getByRole('button', { name: '查看演示路线' }).click()
  await page.locator('#to').selectOption('library')
  await page.getByRole('button', { name: '查看演示路线' }).click()
  await expect(page.locator('#route-status')).toContainText('相同')
  await expect(page.locator('#to')).toBeFocused()
  await expect(page.locator('#route-line')).toBeHidden()
  await page.locator('#to').selectOption('hill')
  await page.getByRole('button', { name: '查看演示路线' }).click()
  await expect(page.locator('#route-status')).toContainText('暂未接入')
  await expect(page.locator('#route-results')).toBeHidden()
  await page.locator('#to').selectOption('market')
  await page.locator('#accessible').check()
  await page.getByRole('button', { name: '查看演示路线' }).click()
  await expect(page.locator('#route-status')).toContainText('零台阶')
  await expect(page.locator('#walk-time')).toHaveText('18 分钟')
  await expect(page.locator('#route-line')).toHaveAttribute(
    'd',
    'M130 160 L130 500 L360 500 L360 337',
  )
})
