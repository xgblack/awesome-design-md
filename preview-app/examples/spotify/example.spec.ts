import { test, expect } from '@playwright/test'
test('spotify: 真实播放、进度、音量、暂停与结束顺播', async ({ page }) => {
  await page.goto('examples/spotify/index.html')
  await page.locator('#play').click()
  await expect(page.locator('#play')).toHaveText('暂停')
  await expect
    .poll(() => page.locator('#audio').evaluate((audio: HTMLAudioElement) => audio.currentTime))
    .toBeGreaterThan(0)
  await page.locator('#volume').fill('35')
  await expect
    .poll(() => page.locator('#audio').evaluate((audio: HTMLAudioElement) => audio.volume))
    .toBeCloseTo(0.35)
  await page.locator('#seek').fill('6')
  await expect
    .poll(() => page.locator('#audio').evaluate((audio: HTMLAudioElement) => audio.currentTime))
    .toBeGreaterThan(5.8)
  await page.locator('#play').click()
  await expect(page.locator('#play')).toHaveText('播放')
  await page.locator('#seek').fill('11.7')
  await page.locator('#play').click()
  await expect(page.locator('#now-title')).toHaveText('Tidal Notes')
  await expect(page.locator('#composition-note')).toContainText('没有采样真实海浪')
})
test('spotify: 队列去重、上移、删除、清空与空队列恢复', async ({ page }) => {
  await page.goto('examples/spotify/index.html')
  await page.locator('[data-enqueue="0"]').click()
  await expect(page.locator('#queue-status')).toContainText('不重复')
  await page.locator('[data-up="1"]').click()
  await expect(page.locator('#queue-items > div').first()).toContainText('Tidal Notes')
  await page.locator('[data-remove="1"]').click()
  await expect(page.locator('#queue-items > div')).toHaveCount(2)
  await page.locator('#clear-queue').click()
  await expect(page.locator('#queue-items')).toContainText('队列为空')
  await page.locator('#next').click()
  await expect(page.locator('#queue-status')).toContainText('队列为空')
  await page.locator('[data-enqueue="2"]').click()
  await page.locator('#next').click()
  await expect(page.locator('#now-title')).toHaveText('Afterglow')
})
test('spotify: 作品类型与文字筛选交集，空态可恢复', async ({ page }) => {
  await page.goto('examples/spotify/index.html')
  await page.locator('[data-kind="ambient"]').click()
  await page.locator('#track-search').fill('Tidal')
  await expect(page.locator('#search-status')).toHaveText('0 段原创作品')
  await expect(page.locator('#search-empty')).toBeVisible()
  await expect(page.locator('#track-search')).toHaveValue('Tidal')
  await page.locator('#reset-search').click()
  await expect(page.locator('.track-row:visible')).toHaveCount(3)
  await expect(page.locator('.albums > button:visible')).toHaveCount(3)
})
test('spotify: 媒体读取失败不能假播放，重试成功清除错误', async ({ page }) => {
  await page.route('**/*.wav*', (route) =>
    route.request().resourceType() === 'media' ? route.abort() : route.continue(),
  )
  await page.goto('examples/spotify/index.html')
  await page.locator('#play').click()
  await expect(page.locator('#audio-error')).toBeVisible()
  await expect(page.locator('#play')).toHaveText('播放')
  await page.unroute('**/*.wav*')
  await page.locator('#retry-audio').click()
  await expect(page.locator('#play')).toHaveText('暂停')
  await expect(page.locator('#audio-error')).toBeHidden()
  await expect
    .poll(() => page.locator('#audio').evaluate((audio: HTMLAudioElement) => audio.currentTime))
    .toBeGreaterThan(0)
})
