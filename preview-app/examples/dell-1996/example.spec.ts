import { test, expect } from '@playwright/test'
test('dell-1996: 搜索和年份组合，空态保留条件并可恢复', async ({ page }) => {
  await page.goto('examples/dell-1996/index.html')
  await page.locator('#search').fill('Notebook')
  await expect(page.locator('#search-status')).toHaveText('1 件馆藏')
  await page.locator('#year').selectOption('1994')
  await expect(page.locator('[data-name]:visible')).toHaveCount(0)
  await expect(page.locator('#search-status')).toContainText('没有找到')
  await expect(page.locator('#search')).toHaveValue('Notebook')
  await page.locator('#reset-search').click()
  await expect(page.locator('[data-name]:visible')).toHaveCount(3)
  await expect(page.locator('table tbody tr')).toHaveCount(4)
})
test('dell-1996: 虚构主板内存和插槽失败边界，修正后生成配置', async ({ page }) => {
  await page.goto('examples/dell-1996/index.html')
  await page.locator('#ram').selectOption('64')
  await page.getByRole('button', { name: 'GENERATE!' }).click()
  await expect(page.locator('#config-result')).toContainText('虚构 BA-94 主板最多支持 16 MB')
  await expect(page.locator('#ram')).toBeFocused()
  await page.locator('#ram').selectOption('16')
  await page.locator('#slot').selectOption('pci')
  await page.getByRole('button', { name: 'GENERATE!' }).click()
  await expect(page.locator('#config-result')).toContainText('没有 PCI 插槽')
  await page.locator('#cpu').selectOption('pentium')
  await page.locator('#ram').selectOption('64')
  await page.getByRole('button', { name: 'GENERATE!' }).click()
  await expect(page.locator('#config-result')).toContainText('Pentium 90 + 64 MB RAM + PCI 卡')
  await expect(page.locator('#slot')).not.toHaveAttribute('aria-invalid', 'true')
})
