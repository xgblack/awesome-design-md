import { test, expect } from '@playwright/test'
test('starbucks: 杯型真实更换渲染，份数限制与摘要联动', async ({ page }) => {
  await page.goto('examples/starbucks/index.html')
  await expect(page.locator('#minus')).toBeDisabled()
  await expect(page.locator('#drink-image')).toHaveAttribute('src', /cup-small/)
  await page.locator('input[name=size][value="大杯"]').check()
  await expect(page.locator('#drink-image')).toHaveAttribute('src', /cup-large/)
  await expect(page.locator('#visual-size')).toHaveText('大杯 / 450 ml')
  await page.locator('#plus').click()
  await page.locator('#plus').click()
  await expect(page.locator('#plus')).toBeDisabled()
  await expect(page.locator('#summary')).toContainText('3 份浓缩')
})
test('starbucks: 奶基失败聚焦，试配盘逐杯编辑替换、删除和空态', async ({ page }) => {
  await page.goto('examples/starbucks/index.html')
  await page.locator('#save-recipe').click()
  await expect(page.locator('#status')).toContainText('请选择奶基')
  await expect(page.locator('#milk')).toBeFocused()
  await page.locator('#milk').selectOption({ label: '燕麦奶' })
  await page.locator('#save-recipe').click()
  await page.locator('#milk').selectOption({ label: '椰奶' })
  await page.locator('#save-recipe').click()
  await page.locator('#tray-open').click()
  await expect(page.locator('#tray-items article')).toHaveCount(2)
  await page.locator('[data-edit-recipe="1"]').click()
  await expect(page.locator('#edit-notice')).toContainText('替换原配方')
  await page.locator('input[name=size][value="大杯"]').check()
  await page.locator('#milk').selectOption({ label: '鲜牛奶' })
  await page.locator('#plus').click()
  await page.locator('#save-recipe').click()
  await expect(page.locator('#tray-count')).toHaveText('2')
  await page.locator('#tray-open').click()
  await expect(page.locator('#tray-items article').first()).toContainText(
    '大杯 · 鲜牛奶 · 2 份浓缩',
  )
  await page.locator('[data-remove-recipe="1"]').click()
  await expect(page.locator('#tray-items article')).toHaveCount(1)
  await expect(page.locator('#tray-items')).toContainText('椰奶')
  await page.locator('#tray-clear').click()
  await expect(page.locator('#tray-items')).toContainText('还是空的')
  await expect(page.locator('#tray-count')).toHaveText('0')
  await expect(page.locator('#tray-clear')).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(page.locator('#tray-open')).toBeFocused()
})
