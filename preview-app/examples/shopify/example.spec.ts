import { test, expect } from '@playwright/test'
test('shopify: 经营阶段是真实DOM工作台', async ({ page }) => {
  await page.goto('examples/shopify/index.html')
  await page.locator('[data-stage=publish]').click()
  await expect(page.locator('#stage-publish')).toBeVisible()
  await expect(page.locator('#inventory-rows tr')).toHaveCount(3)
  await page.locator('[data-stage=fulfil]').click()
  await page.getByRole('button', { name: '完成本地履约步骤' }).click()
  await expect(page.locator('#pack-status')).toContainText('请先完成')
  await page.locator('#pack-check').check()
  await page.locator('#wrap-check').check()
  await page.getByRole('button', { name: '完成本地履约步骤' }).click()
  await expect(page.locator('#pack-status')).toContainText('未生成运单')
})
test('shopify: 上架编辑失败边界和小店联动', async ({ page }) => {
  await page.goto('examples/shopify/index.html')
  await page.locator('[data-edit-product=vase]').click()
  await page.locator('#product-title').fill('')
  await page.getByRole('button', { name: '保存商品草稿' }).click()
  await expect(page.locator('#edit-status')).toContainText('请填写商品名称')
  await page.locator('#product-title').fill('Studio Vase')
  await page.locator('#product-stock').fill('51')
  await page.getByRole('button', { name: '保存商品草稿' }).click()
  await expect(page.locator('#edit-status')).toContainText('0–50之间的整数')
  await page.locator('#product-stock').fill('9')
  await page.locator('#product-published').check()
  await page.getByRole('button', { name: '保存商品草稿' }).click()
  await page.keyboard.press('Escape')
  await expect(page.locator('#objects')).toContainText('Studio Vase')
  await expect(page.locator('#objects')).toContainText('概念库存 9')
  await page.locator('#series').selectOption('ritual')
  await expect(page.locator('#objects article')).toHaveCount(1)
})
