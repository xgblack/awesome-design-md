export function labelFor(key: FacetKey, value: string): string {
  return facets[key].find(([id]) => id === value)?.[1] ?? '待标注'
}
export function isFacetValue(key: FacetKey, value: string) {
  return facets[key].some(([id]) => id === value)
}
